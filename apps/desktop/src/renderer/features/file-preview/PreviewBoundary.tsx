import { Component, type ReactNode } from "react";
export class PreviewBoundary extends Component<
  { children: ReactNode; fail(): void },
  { failed: boolean }
> {
  state = { failed: false };
  static getDerivedStateFromError() {
    return { failed: true };
  }
  componentDidCatch() {
    this.props.fail();
  }
  render() {
    return this.state.failed ? null : this.props.children;
  }
}
